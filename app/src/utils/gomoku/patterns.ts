/** 按 Python 判定顺序注册，同型取最高优先级 */
const PATTERN_GROUPS: Array<{ patterns: number[][]; score: number }> = [
  { patterns: LEAVE, score: -50_000 },
  { patterns: DEFENSE3, score: 900 },
  { patterns: ATTACK3, score: 800 },
  { patterns: DEFENSE2, score: 1_500 },
  { patterns: ATTACK2, score: 2_000 },
  { patterns: ATTACK1_LITTLE, score: 3_000 },
  { patterns: ATTACK1, score: 4_000 },
  { patterns: DEFENSE1, score: 5_000 },
  { patterns: DEFENSE, score: 9_999_999_999 },
  { patterns: ATTACK, score: 100_000_000_000 },
];

function patternKey(arr: number[]): string {
  return arr.join(",");
}

export const PATTERN_SCORES = new Map<string, number>();

for (const group of PATTERN_GROUPS) {
  for (const pattern of group.patterns) {
    const key = patternKey(pattern);
    const prev = PATTERN_SCORES.get(key);
    PATTERN_SCORES.set(key, prev == null ? group.score : Math.max(prev, group.score));
  }
}

import type { AiDifficulty } from "../../types/gomoku";

/** 简单模式：保留防守，显著降低进攻型棋型权重 */
export function adjustScoreForDifficulty(score: number, difficulty: AiDifficulty): number {
  if (difficulty === "standard") return score;
  if (score >= 1_000_000) return score;
  if (score > 2_000) return Math.round(score * 0.35);
  if (score > 0) return Math.round(score * 0.6);
  return score;
}

export function scorePattern(arr: number[], difficulty: AiDifficulty = "standard"): number {
  let value = PATTERN_SCORES.get(patternKey(arr)) ?? -1000;
  for (const num of arr.slice(1, 4)) {
    if (num === 2) value += 50;
    else if (num === 1) value += 1;
  }
  return adjustScoreForDifficulty(value, difficulty);
}
